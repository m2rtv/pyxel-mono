def _pack(rows):
    """Convert list of pattern strings into bit-packed bytes. Internal use."""
    packed = []
    for row in rows:
        byte, bit_count, row_bytes = 0, 0, []
        for ch in row:
            byte = (byte << 1) | (1 if ch == '#' else 0)
            bit_count += 1
            if bit_count == 8:
                row_bytes.append(byte)
                byte, bit_count = 0, 0
        if bit_count > 0:
            row_bytes.append(byte << (8 - bit_count))
        packed.append(bytes(row_bytes))
    return packed


# Pre-pack all glyphs at import time
GLYPHS = {cid: _pack(rows) for cid, rows in _RAW.items()}


