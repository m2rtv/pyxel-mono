class PyxelMono:
    """
    Drop-in wrapper around a PicoGraphics display that replaces its built-in
    text rendering with the Pyxel Mono bitmap font.

    Every method not defined here is forwarded transparently to the underlying
    PicoGraphics display via __getattr__, so set_pen(), clear(), update(),
    rectangle(), circle(), etc. all work exactly as normal.

    Typical usage
    -------------
        from picographics import PicoGraphics, DISPLAY_PICO_DISPLAY
        from pyxel_mono import PyxelMono

        display = PyxelMono(PicoGraphics(display=DISPLAY_PICO_DISPLAY))

        display.set_pen(display.create_pen(255, 255, 255))
        display.text("Hello World", 10, 10, scale=2)
        w = display.measure_text("Hello World", scale=2)
        display.update()
    """

    def __init__(self, display):
        # Store the real PicoGraphics instance as a regular instance attribute.
        # Because _display is set here via normal assignment, it exists in the
        # instance dict and will always be found by normal attribute lookup —
        # __getattr__ is only called when lookup fails, so there is no risk of
        # infinite recursion when __getattr__ accesses self._display.
        self._display = display

    def __getattr__(self, name):
        # Transparently proxy any attribute not defined on PyxelMono to the
        # underlying PicoGraphics display.  This covers set_pen(), clear(),
        # update(), create_pen(), rectangle(), line(), circle(), etc.
        # Accessing self._display here is safe: it is a real instance attribute
        # so Python finds it via normal lookup without re-entering __getattr__.
        return getattr(self._display, name)

    # ------------------------------------------------------------------
    # Text — replaces PicoGraphics built-in font with Pyxel Mono
    # ------------------------------------------------------------------

    def text(self, text, x, y, wordwrap=-1, scale=1, angle=0, spacing=1):
        """
        Draw text using the Pyxel Mono bitmap font.

        Mirrors the PicoGraphics display.text() signature:
            text      : string to render
            x, y      : top-left origin of the first character
            wordwrap  : pixel width at which to wrap to a new line (-1 = off)
            scale     : integer pixel scale factor  (1 = 5 × 12 px per glyph)
            spacing   : extra pixels added between each character

        Colour is taken from the pen currently set on the display via
        display.set_pen() — no colour arguments are needed here, matching
        how PicoGraphics itself works.
        """
        display = self._display
        # Total horizontal advance per character: glyph advance + spacing.
        char_advance = (GLYPH_W + spacing) * scale

        lines = _wrap_lines(text, wordwrap, char_advance)

        for line_idx, line in enumerate(lines):
            cx = x
            ly = y + line_idx * GLYPH_H * scale
            for ch in line:
                cid = ord(ch)
                _draw_char(display, cid, cx, ly, scale)
                cx += char_advance

    def character(self, char, x, y, scale=1):
        """
        Draw a single character by its decimal ASCII code.

        Mirrors the PicoGraphics display.character() signature:
            char  : decimal ASCII code (e.g. 65 for 'A', 38 for '&')
            x, y  : top-left pixel origin
            scale : integer pixel scale factor

        Colour is taken from the pen currently set on the display.
        """
        display = self._display
        _draw_char(display, char, x, y, scale)

    def measure_text(self, text, scale=1, spacing=1, fixed_width=False):
        """
        Return the pixel width of a text string at the given scale.

        Mirrors the PicoGraphics display.measure_text() signature:
            text        : string to measure
            scale       : integer pixel scale factor
            spacing     : extra pixels between characters (matches text())

        All characters — including those without a glyph — contribute one
        char_advance to the total width, matching how text() advances.
        """
        return len(text) * (GLYPH_W + spacing) * scale

