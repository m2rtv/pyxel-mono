def _draw_char(display, cid, cx, y, scale):
    """
    Blit a single glyph onto the display at pixel position (cx, y).

    cid   : character codepoint (key into GLYPHS)
    cx, y : top-left pixel origin of the glyph cell
    scale : integer pixel scale factor

    The current display pen is used for colour; nothing is set here.
    Unknown codepoints are silently skipped (returns False).
    """
    rows = GLYPHS.get(cid)
    if rows is None:
        return False
    for row_idx, row_bytes in enumerate(rows):
        for col in range(GLYPH_W):
            byte_idx = col // 8
            bit_idx  = 7 - (col % 8)
            if row_bytes[byte_idx] & (1 << bit_idx):
                px = cx + col * scale
                py = y  + row_idx * scale
                if scale == 1:
                    display.pixel(px, py)
                else:
                    display.rectangle(px, py, scale, scale)
    return True


def _wrap_lines(text, wordwrap, char_advance):
    """
    Split text into a list of lines that each fit within wordwrap pixels.

    wordwrap     : maximum pixel width per line (<=0 means no wrapping)
    char_advance : pixel advance per character, including any extra spacing

    Words are split on spaces. If a single word is wider than wordwrap it
    is placed on its own line regardless.
    """
    if wordwrap <= 0:
        return [text]

    words = text.split(' ')
    lines = []
    current_line = ''
    current_width = 0

    for word in words:
        word_width = len(word) * char_advance
        if current_line == '':
            # First word on a new line — always accept it.
            current_line = word
            current_width = word_width
        elif current_width + char_advance + word_width <= wordwrap:
            # Space + word fits on the current line.
            current_line += ' ' + word
            current_width += char_advance + word_width
        else:
            # Flush current line and start a new one.
            lines.append(current_line)
            current_line = word
            current_width = word_width

    if current_line:
        lines.append(current_line)

    return lines


